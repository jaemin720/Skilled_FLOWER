def test_no_ft_or_proprio_ablation_and_cpu_autocast():
    model = make_fafmp(use_force_history_adaln=False, use_proprio=False)
    batch = make_batch(1)
    del batch["right_force_history"]
    del batch["robot_obs"]
    with torch.no_grad(), torch.autocast("cpu", dtype=torch.bfloat16):
        actions = model(batch, {"lang_text": batch["lang_text"][0]})
    assert actions.shape == (1, 5, 7) and torch.isfinite(actions).all()
    encoder = FAFMPGRUHistoryEncoder(6, 128, 128)
    with torch.autocast("cpu", dtype=torch.bfloat16):
        latent = encoder(torch.randn(2, 50, 6))
    latent.float().square().mean().backward()
    assert torch.isfinite(encoder.input_proj.weight.grad).all()


def test_training_status_tracks_fafmp_recurrent_updates(tmp_path):
    model = make_fafmp()
    trainer = SimpleNamespace(is_global_zero=True, current_epoch=0, max_epochs=1, global_step=0,
                              num_training_batches=1, optimizers=[], default_root_dir=tmp_path,
                              precision_plugin=SimpleNamespace(scaler=None))
    callback = TrainingStatus()
    callback.on_train_start(trainer, model)
    with torch.no_grad():
        model.force_history_encoder.update_x.weight.add_(0.01)
    trainer.global_step = 1
    callback.on_train_batch_end(trainer, model, torch.tensor(1.0), {}, 0)
    assert json.loads((tmp_path / "training_status.json").read_text())["gru_weight_version_change"] == 1


