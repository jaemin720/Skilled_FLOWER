def test_flow_loss_reaches_encoder_fusion_and_both_adaln_paths():
    model = make_fafmp()
    batch = make_batch()
    batch["right_force_history"].requires_grad_()
    batch["robot_obs"].requires_grad_()
    cond = model.encode_observations(batch)
    assert cond["force_history_embeds"].shape == (2, 8)
    cond["frequency_embeds"].retain_grad()
    loss, _ = model.rf_loss(cond, batch["actions"])
    assert torch.isfinite(loss)
    loss.backward()
    encoder = model.force_history_encoder
    parameters = [encoder.input_proj.weight, encoder.update_x.weight, encoder.update_h.weight,
                  encoder.reset_x.weight, encoder.reset_h.weight, encoder.cand_x.weight,
                  encoder.cand_h.weight, encoder.proj.weight,
                  model.conditioning_mlp.layers[0].weight, model.conditioning_mlp.layers[2].weight,
                  model.t_embedder.mlp[0].weight,
                  model.adaln["eef_delta"].modCX[-1].weight,
                  model.dit[-1].adaLN_modulation[-1].weight,
                  batch["right_force_history"], batch["robot_obs"], cond["frequency_embeds"]]
    for parameter in parameters:
        assert parameter.grad is not None and torch.isfinite(parameter.grad).all()
        assert parameter.grad.abs().sum() > 0


def test_all_condition_branches_influence_shared_and_block_adaln():
    model = make_fafmp()
    cond = model.encode_observations(make_batch())
    shared, blocks = [], []
    shared_hook = model.adaln["eef_delta"].register_forward_pre_hook(
        lambda module, inputs: shared.append(inputs[0].detach().clone()))
    block_hook = model.dit[0].register_forward_pre_hook(
        lambda module, inputs: blocks.append(inputs[1].detach().clone()))
    z, t = torch.randn(2, 5, 7), torch.full((2,), 0.5)
    try:
        baseline = model.dit_forward(z, t, cond)
        variants = [(t + 0.1, cond)]
        for key in ("force_history_embeds", "frequency_embeds", "proprio"):
            variants.append((t, dict(cond, **{key: cond[key] + 0.3})))
        for time, changed in variants:
            result = model.dit_forward(z, time, changed)
            assert not torch.allclose(shared[-1], shared[0])
            assert not torch.allclose(result, baseline)
    finally:
        shared_hook.remove()
        block_hook.remove()
    assert len(shared) == len(blocks) == 5
    for a, b in zip(shared, blocks):
        torch.testing.assert_close(a, b, rtol=0, atol=0)


@pytest.mark.parametrize("use_vlm,readout", [(False, False), (True, False), (True, True)])
def test_concat_keeps_ft_latent_and_optional_vlm_condition(use_vlm, readout):
    model = make_fafmp(use_adaln_cond=use_vlm, use_readout_token=readout)
    cond = model.encode_observations(make_batch(1))
    with patch.object(model.conditioning_mlp, "forward", wraps=model.conditioning_mlp.forward) as fuse:
        result = model.dit_forward(torch.randn(1, 5, 7), torch.ones(1), cond)
    values = fuse.call_args.args
    assert len(values) == 4 + int(use_vlm)
    torch.testing.assert_close(values[0], cond["force_history_embeds"], rtol=0, atol=0)
    assert model.conditioning_mlp.layers[0].in_features == 8 + (3 + int(use_vlm)) * 32
    assert result.shape == (1, 5, 7) and torch.isfinite(result).all()


def test_encoder_is_cached_across_sampling_and_raw_history_fallback_matches():
    model = make_fafmp()
    batch = make_batch(1)
    with patch.object(model.force_history_encoder, "forward", wraps=model.force_history_encoder.forward) as encode:
        with torch.no_grad():
            actions = model(batch, {"lang_text": batch["lang_text"][0]})
    assert encode.call_count == 1 and actions.shape == (1, 5, 7)
    cond = model.encode_observations(batch)
    raw = {k: v for k, v in cond.items() if k != "force_history_embeds"}
    z, t = torch.randn(1, 5, 7), torch.ones(1)
    torch.testing.assert_close(model.dit_forward(z, t, cond), model.dit_forward(z, t, raw))
    with pytest.raises(ValueError, match="force_history_embeds"):
        model.dit_forward(z, t, dict(cond, force_history_embeds=torch.zeros(1, 32)))


def test_new_checkpoint_hyperparameters_restore_strictly():
    model = make_fafmp()
    with patch.object(FLOWERVLA, "_setup_vlm", setup_tiny_vlm):
        restored = FLOWERVLA(**dict(model.hparams)).eval()
    restored._get_text_embeddings = MethodType(tiny_text_embeddings, restored)
    assert list(restored.state_dict()) == list(model.state_dict())
    restored.load_state_dict(model.state_dict(), strict=True)
    batch = make_batch()
    z, t = torch.randn(2, 5, 7), torch.full((2,), 0.5)
    torch.testing.assert_close(model.dit_forward(z, t, model.encode_observations(batch)),
                               restored.dit_forward(z, t, restored.encode_observations(batch)), rtol=0, atol=0)


