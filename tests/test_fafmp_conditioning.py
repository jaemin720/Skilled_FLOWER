def make_fafmp(**overrides):
    settings = dict(force_history_encoder_type="fafmp_gru", force_history_latent_dim=8,
                    adaln_conditioning_type="concat_mlp", adaln_conditioning_hidden_dim=48)
    settings.update(overrides)
    return make_model(**settings)


def copy_dense(layer, parameters):
    with torch.no_grad():
        layer.weight.copy_(torch.tensor(parameters["kernel"]).T)
        if layer.bias is not None:
            layer.bias.copy_(torch.tensor(parameters["bias"]))


def test_original_fafmp_numerical_reference():
    # Generated by the actual FAFMP Flax modules, not by this implementation.
    reference = json.loads((Path(__file__).parent / "fixtures/fafmp_conditioning_reference.json").read_text())
    data = reference["encoder"]
    encoder = FAFMPGRUHistoryEncoder(6, data["hidden_dim"], data["latent_dim"])
    for name in ("input_proj", "update_x", "update_h", "reset_x", "reset_h", "cand_x", "cand_h", "proj"):
        source = {"input_proj": "Dense_0", "proj": "Dense_1"}.get(name, name)
        copy_dense(getattr(encoder, name), data["params"][source])
    torch.testing.assert_close(encoder(torch.tensor(data["input"])), torch.tensor(data["output"]),
                               rtol=2e-5, atol=2e-6)
    data = reference["conditioning_mlp"]
    mlp = FAFMPConditioningMLP(18, *data["hidden_dims"])
    copy_dense(mlp.layers[0], data["params"]["Dense_0"])
    copy_dense(mlp.layers[2], data["params"]["Dense_1"])
    parts = torch.tensor(data["input"]).split([3, 5, 5, 5], dim=-1)
    torch.testing.assert_close(mlp(*parts), torch.tensor(data["output"]), rtol=2e-5, atol=2e-6)


def test_encoder_resets_state_and_uses_temporal_order():
    encoder = FAFMPGRUHistoryEncoder(6, 16, 8)
    history = torch.randn(2, 50, 6)
    expected = encoder(history)
    encoder(torch.randn(3, 50, 6))
    torch.testing.assert_close(encoder(history), expected, rtol=0, atol=0)
    torch.testing.assert_close(torch.cat([encoder(x[None]) for x in history]), expected)
    assert not torch.allclose(encoder(history.flip(1)), expected)
    assert not torch.allclose(encoder(history[:, -1:]), expected)
    assert torch.isfinite(encoder(torch.zeros_like(history))).all()


