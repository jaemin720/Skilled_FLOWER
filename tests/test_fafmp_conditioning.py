@pytest.mark.parametrize("baseline", ["config_default_sfm", "config_default_sfm_no_xy",
                                       "config_default_sfm_unnormalized_state"])
def test_new_configs_preserve_baseline_data_and_training_settings(baseline):
    with initialize_config_dir(config_dir=str(Path(__file__).resolve().parents[1] / "conf")):
        old, new = compose(config_name=baseline), compose(config_name=baseline + "_fafmp")
    for field in ("datamodule", "trainer", "callbacks"):
        assert OmegaConf.to_container(old[field]) == OmegaConf.to_container(new[field])
    for field in ("batch_size", "devices", "seed", "max_epochs", "act_seq_len", "proprio_dims"):
        assert old[field] == new[field]
    assert new.log_dir != old.log_dir
    old_model = OmegaConf.to_container(old.model, resolve=True)
    new_model = OmegaConf.to_container(new.model, resolve=True)
    for key in ("force_history_encoder_type", "adaln_conditioning_type", "adaln_conditioning_hidden_dim"):
        old_model.pop(key)
        new_model.pop(key)
    assert old_model == new_model
    assert new.model.force_history_encoder_type == "fafmp_gru"
    assert new.model.adaln_conditioning_type == "concat_mlp"
